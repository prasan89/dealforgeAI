import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
test('agreement to PDF, Solidity and escrow, with persistence', async ({page}) => {
  const errors = []; page.on('pageerror',e => errors.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{ name:'Good deals start with clarity.' })).toBeVisible();
  await page.screenshot({path:'artifacts/workspace-desktop.png',fullPage:true});
  await expect(page.getByRole('button',{ name:'Analyze agreement' })).toBeDisabled();
  await page.getByRole('button',{ name:'Try an example' }).click();
  await page.getByRole('button',{ name:'Analyze agreement' }).click();
  await expect(page.getByLabel('Client',{exact:true})).toHaveValue('Acme Studio');
  await expect(page.getByLabel('Deadline',{exact:true}).first()).toHaveValue('2026-12-01');
  await page.getByLabel('Governing jurisdiction').fill('California, United States');
  await page.getByLabel('How will the client accept each milestone?').fill('Deliver the agreed design files and responsive website. Client reviews within five business days.');
  await page.getByRole('button',{ name:'Generate contracts',exact:true }).click();
  await expect(page.getByText('Your agreement is ready for review')).toBeVisible();
  const pdfDownload = page.waitForEvent('download'); await page.getByRole('button',{ name:'Download PDF' }).click();
  const pdfFile = await pdfDownload;
  expect(pdfFile.suggestedFilename()).toBe('DealForge-agreement.pdf');
  const pdfBytes = await readFile(await pdfFile.path());
  expect(pdfBytes.subarray(0,5).toString()).toBe('%PDF-');
  expect(pdfBytes.length).toBeGreaterThan(2000);
  await page.getByRole('button',{ name:'Smart contract',exact:true }).click();
  await expect(page.locator('pre')).toContainText('total = 12000000000');
  const solDownload = page.waitForEvent('download'); await page.getByRole('button',{ name:'Download Solidity' }).click();
  expect((await solDownload).suggestedFilename()).toBe('MilestoneEscrow.sol');
  await page.getByRole('button',{ name:'Simulate escrow',exact:true }).click();
  await expect(page.getByRole('button',{ name:'Approve & release' }).first()).toBeDisabled();
  await page.getByRole('button',{ name:'Deposit $12,000.00' }).click();
  await page.getByRole('button',{ name:'Approve & release' }).first().click();
  await expect(page.getByRole('button',{ name:'Released',exact:true })).toBeDisabled();
  await expect(page.locator('.escrow-balances')).toContainText('$9,000.00');
  await page.getByRole('button',{ name:'Client consent',exact:true }).click();
  await expect(page.getByRole('button',{ name:'Approve & release' }).last()).toBeEnabled();
  await page.getByRole('button',{ name:'Contractor consent',exact:true }).click();
  await expect(page.getByText('Cancelled · Remaining balance refunded',{exact:true})).toBeVisible();
  await expect(page.getByRole('button',{ name:'Approve & release' }).last()).toBeDisabled();
  await page.getByRole('button',{ name:/My agreements/ }).click();
  await expect(page.getByRole('heading',{ name:'Website design & development' })).toBeVisible();
  await page.reload();
  await page.getByRole('button',{ name:/My agreements/ }).click();
  await page.getByRole('button',{ name:'Open',exact:true }).click();
  await expect(page.getByText('Your agreement is ready for review')).toBeVisible();
  expect(errors).toEqual([]);
});
test('mobile layout has no horizontal overflow and navigation works', async ({page}) => {
  await page.setViewportSize({width:390,height:844}); await page.goto('/');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({path:'artifacts/workspace-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Toggle navigation'}).click();
  await page.getByRole('button',{name:/My agreements/}).click();
  await expect(page.getByRole('heading',{name:'Your first deal starts here'})).toBeVisible();
});
